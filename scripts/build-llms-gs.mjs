// Builds sheet-scripts/llms.gs (the file pasted into the sheet's Apps Script)
// from assets/llms-core.js (shared with the dashboard) and
// sheet-scripts/llms-server.js. Run: node scripts/build-llms-gs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const server = readFileSync(path.join(root, 'sheet-scripts/llms-server.js'), 'utf8');
const core = readFileSync(path.join(root, 'assets/llms-core.js'), 'utf8');
writeFileSync(path.join(root, 'sheet-scripts/llms.gs'),
  server.trimEnd() + '\n\n/* ============================================================\n' +
  '   Shared with the dashboard (assets/llms-core.js). Generated by\n' +
  '   scripts/build-llms-gs.mjs; edit that file, not this copy.\n' +
  '   ============================================================ */\n\n' + core);
console.log('wrote sheet-scripts/llms.gs');
